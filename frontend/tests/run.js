console.log("microphone resampler (the real AudioWorklet source, run under a fake worklet)");
function runWorklet(rate, blocks) {
  const frames = [];
  let Processor;
  global.sampleRate = rate;
  global.AudioWorkletProcessor = class { constructor() { this.port = { postMessage: (buf) => frames.push(new Int16Array(buf)) }; } };
  global.registerProcessor = (name, cls) => { Processor = cls; };
  (0, eval)(BLB.WORKLET_SOURCE);
  const p = new Processor();
  for (const b of blocks) p.process([[b]]);
  return frames;
}
function sine(rate, hz, amp, seconds) {
  const total = Math.round(rate * seconds), blocks = [];
  for (let start = 0; start < total; start += 128) {
    const n = Math.min(128, total - start), b = new Float32Array(n);
    for (let i = 0; i < n; i++) b[i] = amp * Math.sin(2 * Math.PI * hz * (start + i) / rate);
    blocks.push(b);
  }
  return blocks;
}
const flat = (frames) => frames.flatMap((f) => Array.from(f));
const upCrossings = (xs) => xs.reduce((n, x, i) => n + (i > 0 && xs[i - 1] < 0 && x >= 0 ? 1 : 0), 0);

test("48 kHz in -> exactly 50 frames of 320 samples per second", () => {
  const frames = runWorklet(48000, sine(48000, 440, 0.8, 1));
  assert.strictEqual(frames.length, 50);
  assert.ok(frames.every((f) => f.length === 320));
});
test("a 440 Hz tone comes out at 440 Hz and about the right level", () => {
  const out = flat(runWorklet(48000, sine(48000, 440, 0.8, 1)));
  const crossings = upCrossings(out), peak = Math.max(...out.map(Math.abs));
  assert.ok(crossings >= 437 && crossings <= 443, "crossings=" + crossings);
  assert.ok(peak > 0.77 * 32767 && peak < 0.83 * 32767, "peak=" + peak);
});
test("44.1 kHz (a non-integer ratio) also yields one second of audio at the right pitch", () => {
  const frames = runWorklet(44100, sine(44100, 440, 0.8, 1));
  assert.ok(frames.length >= 49 && frames.length <= 50, "frames=" + frames.length);
  const out = flat(frames), crossings = upCrossings(out);
  assert.ok(crossings >= 430 && crossings <= 443, "crossings=" + crossings);
});
test("silence stays silence", () => {
  assert.ok(flat(runWorklet(48000, sine(48000, 440, 0, 0.5))).every((x) => x === 0));
});
test("an over-range signal clips instead of wrapping around", () => {
  const out = flat(runWorklet(48000, sine(48000, 440, 2.0, 1)));
  assert.ok(Math.max(...out) <= 32767 && Math.min(...out) >= -32768);
  assert.ok(Math.max(...out) > 32000 && Math.min(...out) < -32000);
  const crossings = upCrossings(out);
  assert.ok(crossings >= 437 && crossings <= 443, "crossings=" + crossings);
});

console.log("push-to-talk (AskController)");
function makeAsk() {
  const sent = [], timers = [];
  let t = 0;
  const ask = new BLB.AskController({
    sendText: (o) => sent.push(["text", o.type]),
    sendBinary: (b) => sent.push(["bin", new DataView(b).getUint32(0, false)]),
    now: () => t,
    setTimer: (fn, ms) => { timers.push({ fn, ms, live: true }); return timers.length - 1; },
    clearTimer: (id) => { timers[id].live = false; },
  });
  return { ask, sent, timers, advance: (ms) => { t += ms; }, fire: () => timers.filter((x) => x.live).forEach((x) => { x.live = false; x.fn(); }) };
}
const frame = () => new Int16Array(320);
test("idle frames are not sent, and only the last 25 are kept as pre-roll", () => {
  const h = makeAsk();
  for (let i = 0; i < 40; i++) h.ask.onFrame(frame());
  assert.deepStrictEqual(h.sent, []);
  h.ask.press();
  assert.deepStrictEqual(h.sent[0], ["text", "ask_press"]);
  assert.strictEqual(h.sent.length, 26);
  assert.deepStrictEqual(h.sent.slice(1).map((s) => s[1]), Array.from({ length: 25 }, (_, i) => i));
});
test("a real hold streams live, then sends ask_release only after the post-roll", () => {
  const h = makeAsk();
  h.ask.press(); h.advance(1000);
  h.ask.onFrame(frame()); h.ask.release();
  assert.ok(!h.sent.some((s) => s[1] === "ask_release"), "released too early");
  assert.strictEqual(h.timers[0].ms, 300);
  h.ask.onFrame(frame()); h.ask.onFrame(frame()); // post-roll frames still go out
  assert.strictEqual(h.sent.filter((s) => s[0] === "bin").length, 3);
  h.fire();
  assert.deepStrictEqual(h.sent[h.sent.length - 1], ["text", "ask_release"]);
  assert.strictEqual(h.ask.asking, false);
});
test("a short tap releases immediately, with no post-roll, so the server discards it", () => {
  const h = makeAsk();
  h.ask.press(); h.advance(100); h.ask.release();
  assert.deepStrictEqual(h.sent.map((s) => s[1]), ["ask_press", "ask_release"]);
  assert.strictEqual(h.timers.length, 0);
});
test("pressing again during the post-roll continues the same question", () => {
  const h = makeAsk();
  h.ask.press(); h.advance(1000); h.ask.release();
  h.ask.press();
  h.fire();
  assert.strictEqual(h.sent.filter((s) => s[1] === "ask_press").length, 1);
  assert.ok(!h.sent.some((s) => s[1] === "ask_release"));
  h.advance(500); h.ask.release(); h.fire();
  assert.strictEqual(h.sent.filter((s) => s[1] === "ask_release").length, 1);
});
test("each question restarts its frame sequence at 0, and reset() cancels cleanly", () => {
  const h = makeAsk();
  h.ask.press(); h.ask.onFrame(frame()); h.ask.onFrame(frame()); h.advance(10); h.ask.release();
  h.ask.press(); h.ask.onFrame(frame());
  assert.deepStrictEqual(h.sent.filter((s) => s[0] === "bin").map((s) => s[1]), [0, 1, 0]);
  h.ask.reset();
  assert.strictEqual(h.ask.asking, false);
});

console.log("audio queue");
function fakePlayers(opts) {
  const made = [];
  const create = (blob) => {
    const p = { blob, disposed: false, onended: null, onerror: null,
      play() { return (opts && opts.rejectFirst && made.length === 1 && !opts.allowed) ? Promise.reject(new Error("NotAllowed")) : Promise.resolve(); },
      dispose() { this.disposed = true; } };
    made.push(p);
    return p;
  };
  return { made, create };
}
const tick = () => new Promise((r) => setTimeout(r, 0));
test("clips play one at a time, in queue order", async () => {
  const fp = fakePlayers(), log = [];
  const q = new BLB.AudioQueue({ createPlayer: fp.create, onStart: (m) => log.push("start" + m.n), onEnd: (m) => log.push("end" + m.n) });
  q.enqueue("a", { n: 0 }); q.enqueue("b", { n: 1 }); q.enqueue("c", { n: 2 });
  await tick();
  assert.strictEqual(fp.made.length, 1, "second clip must wait");
  fp.made[0].onended(); await tick();
  fp.made[1].onended(); await tick();
  fp.made[2].onended(); await tick();
  assert.deepStrictEqual(log, ["start0", "end0", "start1", "end1", "start2", "end2"]);
  assert.ok(fp.made.every((p) => p.disposed));
});
test("a clip that fails to decode is skipped, not stuck on", async () => {
  const fp = fakePlayers(), log = [];
  const q = new BLB.AudioQueue({ createPlayer: fp.create, onEnd: (m) => log.push("end" + m.n) });
  q.enqueue("a", { n: 0 }); q.enqueue("b", { n: 1 });
  await tick();
  fp.made[0].onerror(); await tick();
  assert.strictEqual(fp.made.length, 2);
  assert.deepStrictEqual(log, ["end0"]);
});
test("when the browser blocks autoplay the clip is kept, and plays after resume()", async () => {
  const opts = { rejectFirst: true, allowed: false }, fp = fakePlayers(opts);
  let blocked = 0;
  const q = new BLB.AudioQueue({ createPlayer: fp.create, onBlocked: () => blocked++ });
  q.enqueue("a", { n: 0 }); await tick();
  assert.strictEqual(blocked, 1);
  opts.allowed = true;
  q.resume(); await tick();
  assert.strictEqual(fp.made.length, 2);
  assert.strictEqual(fp.made[1].blob, "a");
});
test("clear() stops the current clip and drops the rest", async () => {
  const fp = fakePlayers();
  const q = new BLB.AudioQueue({ createPlayer: fp.create });
  q.enqueue("a", { n: 0 }); q.enqueue("b", { n: 1 }); await tick();
  q.clear(); await tick();
  assert.strictEqual(fp.made.length, 1);
  assert.ok(fp.made[0].disposed);
});

