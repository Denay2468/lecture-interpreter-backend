const api = require("../js/api.js");
function memStorage() { const m = new Map(); return { getItem: (k) => (m.has(k) ? m.get(k) : null), setItem: (k, v) => m.set(k, String(v)), removeItem: (k) => m.delete(k) }; }
const resp = (status, json) => ({ ok: status < 400, status, json: async () => json });
const tokensFor = (n) => ({ access_token: "acc" + n, refresh_token: "ref" + n, expires_in: 900, user: { id: "u", role: "LECTURER", full_name: "T" } });
const sessionRec = (acc, ms) => ({ access_token: acc, refresh_token: "r-" + acc, expires_at: Date.now() + ms, user: { id: "u", role: "LECTURER", full_name: "T" } });
function setup(rec, handler) {
  global.sessionStorage = memStorage();
  if (rec) global.sessionStorage.setItem("blb.session", JSON.stringify(rec));
  const calls = [];
  global.fetch = async (url, o) => {
    const c = { method: (o && o.method) || "GET", path: url.replace(/^https?:\/\/[^/]+/, ""), auth: o && o.headers && o.headers.Authorization, body: o && o.body ? JSON.parse(o.body) : undefined };
    calls.push(c);
    return handler(c, calls);
  };
  return calls;
}
let chain = Promise.resolve(); // these tests share global fetch/storage, so they run one after another
function serial(name, fn) { pending.push((chain = chain.then(() => fn().then(() => report(name), (e) => report(name, e))))); }
const later = (ms) => new Promise((r) => setTimeout(r, ms));

serial("signIn stores the session and accessToken() returns it", async () => {
  setup(null, (c) => resp(200, tokensFor(1)));
  const s = await api.signIn("a@x.id", "pw");
  assert.strictEqual(s.user.role, "LECTURER");
  assert.strictEqual(api.session.get().access_token, "acc1");
  assert.strictEqual(await api.accessToken(), "acc1");
});
serial("an access token about to expire is refreshed first, and parallel requests share one refresh", async () => {
  const calls = setup(sessionRec("old", 5000), async (c) => {
    if (c.path === "/auth/refresh") { await later(15); return resp(200, tokensFor(2)); }
    return resp(200, []);
  });
  await Promise.all([api.get("/rooms"), api.get("/rooms")]);
  assert.strictEqual(calls.filter((c) => c.path === "/auth/refresh").length, 1);
  assert.deepStrictEqual(calls.filter((c) => c.path === "/rooms").map((c) => c.auth), ["Bearer acc2", "Bearer acc2"]);
});
serial("a 401 triggers one refresh and the request is retried with the new token", async () => {
  const calls = setup(sessionRec("old", 600000), (c) => {
    if (c.path === "/auth/refresh") return resp(200, tokensFor(3));
    return c.auth === "Bearer old" ? resp(401, { detail: "expired" }) : resp(200, [{ ok: true }]);
  });
  assert.deepStrictEqual(await api.get("/rooms"), [{ ok: true }]);
  assert.deepStrictEqual(calls.map((c) => c.path + ":" + c.auth), ["/rooms:Bearer old", "/auth/refresh:undefined", "/rooms:Bearer acc3"]);
});
serial("when the refresh token is rejected the session is cleared and the error says so", async () => {
  setup(sessionRec("old", 1000), () => resp(401, { detail: "Your session has expired. Sign in again." }));
  await assert.rejects(api.get("/rooms"), (e) => e.status === 401 && /expired/.test(e.message));
  assert.strictEqual(api.session.get(), null);
});
serial("a network failure becomes a readable error", async () => {
  setup(sessionRec("a", 600000), () => { throw new Error("boom"); });
  await assert.rejects(api.get("/rooms"), (e) => e.status === 0 && /reach the server/.test(e.message));
});
serial("server error details reach the caller", async () => {
  setup(null, () => resp(422, { detail: "Use at least 10 characters." }));
  await assert.rejects(api.activate("a@x.id", "123456", "short"), (e) => e.status === 422 && e.message === "Use at least 10 characters.");
});
serial("requireRole redirects to the login page for a missing or wrong role", async () => {
  const nav = [];
  global.BLB_NAVIGATE = (u) => nav.push(u);
  setup(null, () => resp(200, {}));
  assert.strictEqual(api.requireRole("LECTURER"), null);
  setup(sessionRec("a", 600000), () => resp(200, {}));
  assert.strictEqual(api.requireRole("ADMIN"), null);
  assert.ok(api.requireRole("LECTURER", "ADMIN"));
  assert.deepStrictEqual(nav, ["login.html", "login.html"]);
  delete global.BLB_NAVIGATE;
});
serial("signOut clears the session even if the server can't be reached", async () => {
  setup(sessionRec("a", 600000), () => { throw new Error("offline"); });
  await api.signOut();
  assert.strictEqual(api.session.get(), null);
});

